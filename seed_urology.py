"""
seed_urology.py — Deterministic & Multimodal Urology Database Seeder for UroCura OS.

Populates `urology_coding.db` with:
  1. Temporal Version-Controlled CPT (2026 vs. 2027) & HCPCS Level II Catalog
  2. CMS MPFS RVU & GPCI Locality Tables (including 2026 -2.5% Efficiency Adjustment & QP/non-QP CF)
  3. CMS NCCI Procedure-to-Procedure (PTP) Bundling Edits (Chapter 7 Genitourinary Pairs)
  4. CMS NCCI Medically Unlikely Edits (MUE Daily Unit Caps & MAI Indicators)
  5. Interpretive Authority Repository (AMA CPT Assistant, NCCI Policy Manual Ch. 7, Urology Specialty Rules)
  6. Medicare Coverage Database (MAC Contractors, LCDs & Billing/Coding Articles with Wellpoint Federal alias)
  7. CMS PUF + NPPES NPI Urology Specialty Peer Benchmarks (Cold-Open Outbound Decile Analyzer)
  8. 8 End-to-End Multimodal Clinical Encounters (Handwritten OCR, Operative PDF, Pathology, DICOM + 3-Way Diff)
"""

import json
